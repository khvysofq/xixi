import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { JSDOM, VirtualConsole } = require('../scripts/deps.cjs');
const { TextDecoder, TextEncoder } = require('node:util');
const PAGE=new URL('../public/tools/resume-check/index.html', import.meta.url);
const vc=new VirtualConsole(); vc.on('jsdomError',(e)=>console.log('JSDOMERR:',String(e&&e.message||e).slice(0,300)));
const dom=new JSDOM(fs.readFileSync(PAGE,'utf8'),{runScripts:'dangerously',pretendToBeVisual:true,url:'http://localhost/',virtualConsole:vc,beforeParse(w){w.TextDecoder=TextDecoder;w.TextEncoder=TextEncoder;}});
const w=dom.window;
await new Promise(r=>setTimeout(r,100));
const JSZipNode = require('../vendor/jszip.min.js');
const zip=new JSZipNode();
zip.file('word/document.xml','<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>王五</w:t></w:r></w:p><w:p><w:r><w:t>男，31岁</w:t></w:r></w:p><w:p><w:r><w:t>2015.09-2019.06 中南大学 物流管理 本科</w:t></w:r></w:p><w:p><w:r><w:t>工作经历 2019.07-至今 广州速达物流有限公司 仓储主管</w:t></w:r></w:p></w:body></w:document>');
const buf=await zip.generateAsync({type:'nodebuffer'});
const u2=new w.Uint8Array(Array.from(buf));
const f2=new w.File([u2],'r.docx');
const ev=new w.Event('drop',{bubbles:true,cancelable:true});
ev.dataTransfer={files:[f2]};
w.document.getElementById('drop').dispatchEvent(ev);
